import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { getBastPdfUrl } from "@/api/bast";
import { usePdfBlobUrl } from "@/hooks/usePdfBlobUrl";
import type { BAST } from "../types";
import { Loader2, AlertCircle } from "lucide-react";

interface BASTPdfViewerProps {
  bast: BAST | null;
  onOpenChange: (open: boolean) => void;
}

export function BASTPdfViewer({ bast, onOpenChange }: BASTPdfViewerProps) {
  const apiUrl = bast ? getBastPdfUrl(bast.id) : null;
  const { blobUrl, isLoading, error } = usePdfBlobUrl(apiUrl);

  if (!bast) return null;

  return (
    <Dialog open={!!bast} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-4xl max-h-[95vh] flex flex-col p-0">
        <DialogHeader className="p-4 pb-2 shrink-0">
          <DialogTitle>BAST PDF - {bast.documentInfo.bastNumber}</DialogTitle>
        </DialogHeader>

        <div className="flex-1 flex flex-col min-h-0 px-4 pb-4">
          {isLoading && (
            <div className="w-full flex-1 min-h-[500px] flex items-center justify-center border border-slate-200 dark:border-white/10 rounded-lg bg-slate-50 dark:bg-slate-900">
              <Loader2 className="h-8 w-8 animate-spin text-slate-400" />
            </div>
          )}
          {error && (
            <div className="w-full flex-1 min-h-[500px] flex flex-col items-center justify-center gap-2 border border-red-200 dark:border-red-800 rounded-lg bg-red-50 dark:bg-red-950/20 text-red-500">
              <AlertCircle className="h-8 w-8" />
              <p className="text-sm font-medium">Failed to load PDF</p>
              <p className="text-xs text-red-400">{error}</p>
            </div>
          )}
          {blobUrl && (
            <iframe
              src={blobUrl}
              title={`BAST ${bast.documentInfo.bastNumber}`}
              className="w-full flex-1 min-h-[500px] border border-slate-200 dark:border-white/10 rounded-lg bg-white dark:bg-slate-900"
            />
          )}
          <p className="text-[10px] text-slate-400 mt-2">
            PDF is generated by the backend. If you see a blank page, the
            backend may not be configured yet.
          </p>
        </div>
      </DialogContent>
    </Dialog>
  );
}
